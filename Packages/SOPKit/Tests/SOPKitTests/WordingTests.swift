import ShotModel
import XCTest
@testable import SOPKit

/// General wording and per-run instructions (2026-11). The Specific prompt must stay
/// exactly what it was; General replaces the paragraphs that tell the model to name
/// things rather than contradicting them; the author's own words keep their
/// specifics in either wording.
final class WordingTests: XCTestCase {

    // MARK: Specific is unchanged

    /// Fingerprint of every Specific prompt variant as sent before the wording
    /// choice existed (taken from the code at 1a26685 before the change): each tone,
    /// with and without standing custom instructions, plus both title instructions.
    /// A deliberate prompt edit updates this; an accidental one fails here.
    static let specificFingerprint = "9bbf6208ee4cc1e4fb0098fae18702544b795966b52d48157219252d059041fb"

    private func fingerprint(run: SopRun?) -> String {
        var all: [String] = []
        for tone in [SopTone.professional, .friendly, .concise, .detailed] {
            for custom in ["", "Use our house style."] {
                all.append(buildSystemPrompt(settings: SopSettings(tone: tone, customInstructions: custom), run: run))
            }
        }
        for auto in [true, false] {
            all.append(titleInstruction(currentName: "Project 2026-11-17 09.00", isAutoGenerated: auto,
                                        wording: run?.wording ?? .specific))
        }
        return SHA256.hash(data: Data(all.joined(separator: "\u{0}").utf8)).map { String(format: "%02x", $0) }.joined()
    }

    func testTheSpecificPromptIsByteIdenticalToBefore() {
        XCTAssertEqual(fingerprint(run: nil), Self.specificFingerprint)
        XCTAssertEqual(fingerprint(run: SopRun(wording: .specific)), Self.specificFingerprint,
                       "an explicit Specific run with no instructions is the same prompt")
        XCTAssertEqual(fingerprint(run: SopRun(wording: .specific, instructions: "  \n ")), Self.specificFingerprint,
                       "blank run instructions add nothing")
    }

    // MARK: General

    private var general: String { buildSystemPrompt(settings: SopSettings(), run: SopRun(wording: .general)) }
    private var specific: String { buildSystemPrompt(settings: SopSettings()) }

    /// The paragraphs that tell the model to name the clicked control are REPLACED,
    /// not followed by a contradiction for the model to resolve.
    func testGeneralReplacesTheNamingParagraphs() {
        XCTAssertTrue(specific.contains(PromptParagraph.ring))
        XCTAssertTrue(specific.contains(PromptParagraph.element))
        XCTAssertFalse(general.contains(PromptParagraph.ring))
        XCTAssertFalse(general.contains(PromptParagraph.element))
        XCTAssertFalse(general.contains("name the control by what the user actually sees"))
        XCTAssertTrue(general.contains(PromptParagraph.ringGeneral))
        XCTAssertTrue(general.contains(PromptParagraph.elementGeneral))
        XCTAssertTrue(general.contains(PromptParagraph.generalScope))
        XCTAssertFalse(specific.contains("Wording: GENERAL"))
    }

    /// Everything else is shared, so the two wordings cannot drift apart on
    /// numbering, ordering or the redaction rule.
    func testGeneralKeepsEveryOtherParagraph() {
        for p in [PromptParagraph.role, PromptParagraph.plan, PromptParagraph.numbering, PromptParagraph.order] {
            XCTAssertTrue(general.contains(p))
        }
    }

    /// The author's words are carved out explicitly: generalizing applies to what
    /// the model writes, never to author blocks, an author overview or a name a
    /// person wrote.
    func testTheAuthorsOwnWordsKeepTheirSpecifics() {
        let scope = PromptParagraph.generalScope
        XCTAssertTrue(scope.contains("author block"))
        XCTAssertTrue(scope.contains("overview the author wrote"))
        XCTAssertTrue(scope.contains("project name a person wrote"))
        XCTAssertTrue(scope.contains("keep every name, value and fact"))
    }

    func testAnAppGeneratedNameIsReplacedInGeneralTerms() {
        let t = titleInstruction(currentName: "Project 1", isAutoGenerated: true, wording: .general)
        XCTAssertTrue(t.contains("in general terms"))
        XCTAssertTrue(t.contains("MUST be replaced"))
        XCTAssertFalse(t.contains("Configuring VPN access in the admin console"), "the Specific example names a product area")
    }

    /// A name a person wrote is theirs: the same instruction in either wording.
    func testANamePersonWroteIsTreatedTheSameInEitherWording() {
        XCTAssertEqual(titleInstruction(currentName: "Badge printer setup", isAutoGenerated: false, wording: .general),
                       titleInstruction(currentName: "Badge printer setup", isAutoGenerated: false, wording: .specific))
    }

    // MARK: Instructions for one run

    func testRunInstructionsComeLastAndAreCapped() throws {
        let s = SopSettings(customInstructions: "House style.")
        let p = buildSystemPrompt(settings: s, run: SopRun(wording: .specific, instructions: "  Call it the portal.  "))
        XCTAssertTrue(p.hasSuffix("Instructions from the author for this SOP:\nCall it the portal."))
        let standing = try XCTUnwrap(p.range(of: "House style."))
        let once = try XCTUnwrap(p.range(of: "Call it the portal."))
        XCTAssertLessThan(standing.lowerBound, once.lowerBound, "standing instructions first, this SOP's last")
        let long = String(repeating: "y", count: SOP_RUN_INSTRUCTIONS_MAX + 50)
        let capped = buildSystemPrompt(settings: SopSettings(), run: SopRun(instructions: long))
        XCTAssertTrue(capped.hasSuffix(String(repeating: "y", count: SOP_RUN_INSTRUCTIONS_MAX)))
        XCTAssertFalse(capped.contains(String(repeating: "y", count: SOP_RUN_INSTRUCTIONS_MAX + 1)))
    }

    // MARK: Settings and the remembered choice

    private func decode(_ json: String) throws -> SopSettings {
        try JSONDecoder().decode(SopSettings.self, from: Data(json.utf8))
    }

    func testTheWordingSettingDecodesTolerantly() throws {
        XCTAssertEqual(try decode(#"{"wording":"general","tone":"friendly"}"#).wording, .general)
        XCTAssertEqual(try decode(#"{"tone":"friendly"}"#).wording, DEFAULT_SOP_WORDING, "missing: the default")
        let odd = try decode(#"{"wording":"brief","tone":"friendly"}"#)
        XCTAssertEqual(odd.wording, DEFAULT_SOP_WORDING, "unknown: the default")
        XCTAssertEqual(odd.tone, .friendly, "and nothing else is lost")
        let s = SopSettings(wording: .general)
        XCTAssertEqual(try JSONDecoder().decode(SopSettings.self, from: JSONEncoder().encode(s)), s)
    }

    func testTheDialogStartsFromTheProjectsRememberedChoice() {
        let generalSettings = SopSettings(wording: .general)
        XCTAssertEqual(SopRun(remembered: nil, settings: generalSettings), SopRun(wording: .general),
                       "never chosen: Settings")
        XCTAssertEqual(SopRun(remembered: SopRunOptions(wording: .specific, instructions: "x"), settings: generalSettings),
                       SopRun(wording: .specific, instructions: "x"),
                       "chosen: the project's choice, even when Settings now says otherwise")
        var unknown = SopRunOptions(instructions: "keep me")
        unknown.wording = "brief"
        XCTAssertEqual(SopRun(remembered: unknown, settings: generalSettings), SopRun(wording: .general, instructions: "keep me"),
                       "a wording this build does not know falls back to Settings; the instructions stay")
    }

    /// What is remembered is the explicit choice, the default included, and any
    /// field a newer build stored alongside it survives.
    func testRememberingKeepsTheExplicitDefaultAndUnknownFields() {
        let existing = SopRunOptions(wording: .general, instructions: "old", extra: ["audience": .string("new hires")])
        let saved = SopRun(wording: .specific, instructions: "new").remembered(over: existing)
        XCTAssertEqual(saved.wording, "specific")
        XCTAssertEqual(saved.instructions, "new")
        XCTAssertEqual(saved.extra["audience"], .string("new hires"))
        XCTAssertFalse(saved.isEmpty)
    }

    // MARK: The requests carry the run

    private func system(_ req: URLRequest) throws -> String {
        let body = try XCTUnwrap(try JSONSerialization.jsonObject(with: XCTUnwrap(req.httpBody)) as? [String: Any])
        let blocks = try XCTUnwrap(body["system"] as? [[String: Any]])
        return blocks.compactMap { $0["text"] as? String }.joined()
    }

    func testGenerationAndItsRepairTurnUseTheRunsWordingAndInstructions() async throws {
        let (store, path, dir) = try await makeProject(shots: 1)
        let m = try await store.openProject(at: path).manifest
        let rec = SonnetFiveFiveTests.Recorder()
        let filler = #"{"title":"A Real Title","intro":null,"steps":[{"stepNumber":1,"kind":"screenshot","caption":"Placeholder","body":"TBD","sectionHeading":null,"sectionBody":null}]}"#
        let good = #"{"title":"A Real Title","intro":null,"steps":[{"stepNumber":1,"kind":"screenshot","caption":"Open the app","body":"Click the app.","sectionHeading":null,"sectionBody":null}]}"#
        let queue = SopValidationTests.Script([(sseLines(json: filler), ResponseHead(status: 200)),
                                               (sseLines(json: good), ResponseHead(status: 200))])
        var svc = SopService(
            client: ClaudeClient(transport: MockTransport(streamHandler: { req in rec.add(req); return queue.next(req) })),
            keyStore: StubKeyStore())
        svc.sleep = { _ in }
        _ = try await svc.generate(dir: dir, manifest: m, settings: SopSettings(),
                                   run: SopRun(wording: .general, instructions: "Call it the portal."))
        XCTAssertEqual(rec.all.count, 2, "first answer plus one repair turn")
        for req in rec.all {
            let sys = try system(req)
            XCTAssertTrue(sys.contains("Wording: GENERAL"))
            XCTAssertTrue(sys.hasSuffix("Instructions from the author for this SOP:\nCall it the portal."))
        }
    }

    func testWithoutARunTheSettingsWordingIsUsed() async throws {
        let (store, path, dir) = try await makeProject(shots: 1)
        let m = try await store.openProject(at: path).manifest
        let rec = SonnetFiveFiveTests.Recorder()
        let good = #"{"title":"A Real Title","intro":null,"steps":[{"stepNumber":1,"kind":"screenshot","caption":"Open the app","body":"Click the app.","sectionHeading":null,"sectionBody":null}]}"#
        var svc = SopService(
            client: ClaudeClient(transport: MockTransport(streamHandler: { req in
                rec.add(req); return (sseLines(json: good), ResponseHead(status: 200))
            })),
            keyStore: StubKeyStore())
        svc.sleep = { _ in }
        _ = try await svc.generate(dir: dir, manifest: m, settings: SopSettings(wording: .general))
        XCTAssertTrue(try system(try XCTUnwrap(rec.all.first)).contains("Wording: GENERAL"))
    }

    /// The title instruction lives in the user message, not the system prompt, so
    /// the system-prompt checks above cannot see it. An app-generated name is
    /// Claude's to replace, and it follows the wording chosen in the dialog even
    /// when Settings says the opposite. (`makeProject` names its project "Test SOP",
    /// a name a person wrote, which takes the branch where wording does not matter.)
    func testTheTitleInstructionFollowsTheRunsWordingNotTheSettings() async throws {
        let (store, path, dir) = try await makeProject(shots: 1)
        var m = try await store.openProject(at: path).manifest
        m.title = "Project 2026/11/17 13:27:00"
        XCTAssertTrue(ProjectStore.isAutoGeneratedTitle(m.title), "fixture must hit the auto-name branch")

        func userText(settings: SopSettings, run: SopRun) throws -> String {
            let req = try assembleRequest(dir: dir, manifest: m, settings: settings, run: run)
            return req.messages
                .flatMap { ($0["content"] as? [[String: Any]]) ?? [] }
                .compactMap { $0["text"] as? String }
                .joined(separator: "\n")
        }
        let general = titleInstruction(currentName: m.title, isAutoGenerated: true, wording: .general)
        let specific = titleInstruction(currentName: m.title, isAutoGenerated: true, wording: .specific)
        XCTAssertNotEqual(general, specific)

        let chosenGeneral = try userText(settings: SopSettings(wording: .specific), run: SopRun(wording: .general))
        XCTAssertTrue(chosenGeneral.contains(general), "General chosen in the dialog, Specific in Settings")
        XCTAssertFalse(chosenGeneral.contains(specific))

        let chosenSpecific = try userText(settings: SopSettings(wording: .general), run: SopRun(wording: .specific))
        XCTAssertTrue(chosenSpecific.contains(specific), "Specific chosen in the dialog, General in Settings")
        XCTAssertFalse(chosenSpecific.contains(general))
    }

    /// The estimate counts the prompt that will be sent, run instructions included.
    func testTheEstimateCountsTheRunsPrompt() async throws {
        let (store, path, dir) = try await makeProject(shots: 1)
        let m = try await store.openProject(at: path).manifest
        let rec = SonnetFiveFiveTests.Recorder()
        let svc = SopService(
            client: ClaudeClient(transport: MockTransport(dataHandler: { req in
                rec.add(req); return (Data(#"{"input_tokens":10}"#.utf8), ResponseHead(status: 200))
            })),
            keyStore: StubKeyStore())
        _ = try await svc.estimate(dir: dir, manifest: m, settings: SopSettings(),
                                   run: SopRun(wording: .general, instructions: "Call it the portal."))
        let sys = try system(try XCTUnwrap(rec.all.first))
        XCTAssertTrue(sys.contains("Wording: GENERAL"))
        XCTAssertTrue(sys.contains("Call it the portal."))
    }
}
